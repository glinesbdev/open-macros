"""Generates the Open Macros adaptive icon (VectorDrawable XML) and docs/icon-512.png from one geometry.
Run from the repo root: python3 docs/gen_icon.py (needs Pillow for the PNG)."""
import math

C, R, W = 54.0, 22.0, 8.0                      # ring centre, radius, stroke (inside the 33dp safe radius)
ARCS = [(14, 106), (134, 226), (254, 346)]     # degrees clockwise from 12 o'clock: protein, carbs, fat
COLORS = ["#FF8A80", "#80C8F0", "#FFD166"]
LEAF_COLOR, BG = "#B9F6CA", "#17332A"
TILT = math.radians(35)

def pt(deg, r=R):
    a = math.radians(deg - 90)
    return C + r * math.cos(a), C + r * math.sin(a)

def rot(x, y):
    dx, dy = x - C, y - C
    return C + dx * math.cos(TILT) - dy * math.sin(TILT), C + dx * math.sin(TILT) + dy * math.cos(TILT)

# Leaf: two cubic curves between tip (top) and base (bottom), then tilted.
LEAF = [((54, 43), (61, 46), (63, 56), (54, 65)), ((54, 65), (45, 56), (47, 46), (54, 43))]

def leaf_path():
    segs = [[rot(*p) for p in seg] for seg in LEAF]
    s = f"M{segs[0][0][0]:.2f},{segs[0][0][1]:.2f}"
    for seg in segs:
        s += " C" + " ".join(f"{x:.2f},{y:.2f}" for x, y in seg[1:])
    return s + " Z"

def vector(mono):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by docs/gen_icon.py. A macro ring (protein / carbs / fat) around a leaf. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
    for (s, e), c in zip(ARCS, COLORS):
        (x1, y1), (x2, y2) = pt(s), pt(e)
        col = "#FFFFFFFF" if mono else c
        out.append(f'    <path android:pathData="M{x1:.2f},{y1:.2f} A{R},{R} 0 0,1 {x2:.2f},{y2:.2f}" android:strokeColor="{col}" '
                   f'android:strokeWidth="{W}" android:strokeLineCap="round" android:fillColor="#00000000" />')
    out.append(f'    <path android:pathData="{leaf_path()}" android:fillColor="{"#FFFFFFFF" if mono else LEAF_COLOR}" />')
    out.append('</vector>')
    return "\n".join(out) + "\n"

open("app/src/main/res/drawable/ic_launcher_foreground.xml", "w").write(vector(False))
open("app/src/main/res/drawable/ic_launcher_monochrome.xml", "w").write(vector(True))

try:
    from PIL import Image, ImageDraw
except ImportError:
    raise SystemExit("Pillow not installed; skipped PNG")
S = 4; N = 512 * S; k = N / 108
img = Image.new("RGBA", (N, N), (0, 0, 0, 0)); d = ImageDraw.Draw(img)
d.rounded_rectangle([0, 0, N - 1, N - 1], radius=int(N * 0.22), fill=BG)
r, w = R * k, W * k
for (s, e), c in zip(ARCS, COLORS):
    d.arc([C * k - r - w / 2, C * k - r - w / 2, C * k + r + w / 2, C * k + r + w / 2], start=s - 90, end=e - 90, fill=c, width=int(w))
    for a in (s, e):
        x, y = pt(a); d.ellipse([x * k - w / 2, y * k - w / 2, x * k + w / 2, y * k + w / 2], fill=c)
def bez(p0, p1, p2, p3, n=40):
    return [tuple((1-t)**3*p0[i] + 3*(1-t)**2*t*p1[i] + 3*(1-t)*t*t*p2[i] + t**3*p3[i] for i in range(2)) for t in (j / n for j in range(n + 1))]
pts = [rot(*p) for seg in LEAF for p in bez(*seg)]
d.polygon([(x * k, y * k) for x, y in pts], fill=LEAF_COLOR)
img.resize((512, 512), Image.LANCZOS).save("docs/icon-512.png")
